//! Waveform synthesis.
//!
//! [`Oscillator`] generates one periodic waveform at a time using 32-bit phase
//! accumulation. It uses a compact sine table with linear interpolation rather
//! than floating-point math, so output is deterministic and cheap on bare
//! metal.

use crate::sample::Sample;

const NOISE_SEED: u32 = 0x1234_5678;

/// A quarter-wave-friendly table of `sin(2*pi*i/64) * 32767`.
const SINE_TABLE: [i16; 64] = [
    0, 3212, 6393, 9512, 12539, 15446, 18204, 20787, 23170, 25329, 27245, 28898, 30273, 31356,
    32137, 32609, 32767, 32609, 32137, 31356, 30273, 28898, 27245, 25329, 23170, 20787, 18204,
    15446, 12539, 9512, 6393, 3212, 0, -3212, -6393, -9512, -12539, -15446, -18204, -20787, -23170,
    -25329, -27245, -28898, -30273, -31356, -32137, -32609, -32767, -32609, -32137, -31356, -30273,
    -28898, -27245, -25329, -23170, -20787, -18204, -15446, -12539, -9512, -6393, -3212,
];

/// The shape generated by an [`Oscillator`].
#[derive(Clone, Copy, PartialEq, Eq, Hash, Debug)]
pub enum Waveform {
    /// Smooth sine wave from a lookup table.
    Sine,
    /// Half-positive, half-negative square wave.
    Square,
    /// Linear triangle wave.
    Triangle,
    /// Rising sawtooth.
    Sawtooth,
    /// Pseudo-random noise from a 32-bit xorshift generator.
    Noise,
}

/// A monophonic oscillator.
///
/// Phase is stored as a `u32` where `0` and `u32::MAX` both represent the
/// start of the cycle. The oscillator is cheap to copy and has no heap
/// allocation.
#[derive(Clone, Copy, Debug)]
pub struct Oscillator {
    waveform: Waveform,
    frequency: u32,
    amplitude: u16,
    phase: u32,
    noise: u32,
}

impl Oscillator {
    /// Creates an oscillator.
    ///
    /// `frequency` is in Hz. `amplitude` is the peak; its magnitude is used
    /// and clamped to [`Sample::MAX`].
    pub const fn new(waveform: Waveform, frequency: u32, amplitude: Sample) -> Self {
        Self {
            waveform,
            frequency,
            amplitude: clamp_amplitude(amplitude),
            phase: 0,
            noise: NOISE_SEED,
        }
    }

    /// The current waveform.
    pub const fn waveform(&self) -> Waveform {
        self.waveform
    }

    /// The current frequency in Hz.
    pub const fn frequency(&self) -> u32 {
        self.frequency
    }

    /// The current peak amplitude (`0..=32767`).
    pub const fn amplitude(&self) -> u16 {
        self.amplitude
    }

    /// The current 32-bit phase.
    pub const fn phase(&self) -> u32 {
        self.phase
    }

    /// Changes the waveform without resetting the phase.
    pub fn set_waveform(&mut self, waveform: Waveform) {
        self.waveform = waveform;
    }

    /// Changes the frequency without resetting the phase.
    pub fn set_frequency(&mut self, frequency: u32) {
        self.frequency = frequency;
    }

    /// Changes the peak amplitude without resetting the phase.
    pub fn set_amplitude(&mut self, amplitude: Sample) {
        self.amplitude = clamp_amplitude(amplitude);
    }

    /// Resets phase and noise state.
    pub fn reset(&mut self) {
        self.phase = 0;
        self.noise = NOISE_SEED;
    }

    /// Produces the next sample and advances the phase.
    ///
    /// Returns silence when `sample_rate` or the frequency is zero.
    pub fn next_sample(&mut self, sample_rate: u32) -> Sample {
        if sample_rate == 0 || self.frequency == 0 {
            return Sample::SILENCE;
        }

        let value = self.value();
        self.advance(sample_rate);
        self.scaled(value)
    }

    fn value(&mut self) -> i32 {
        match self.waveform {
            Waveform::Sine => sine(self.phase),
            Waveform::Square => {
                if self.phase < 0x8000_0000 {
                    32_767
                } else {
                    -32_767
                }
            }
            Waveform::Triangle => triangle(self.phase),
            Waveform::Sawtooth => sawtooth(self.phase),
            Waveform::Noise => self.next_noise(),
        }
    }

    fn scaled(&self, value: i32) -> Sample {
        let scaled = (value as i64 * self.amplitude as i64) / i16::MAX as i64;
        Sample::from_i16(scaled.clamp(i16::MIN as i64, i16::MAX as i64) as i16)
    }

    fn advance(&mut self, sample_rate: u32) {
        let increment = ((self.frequency as u64) << 32) / sample_rate as u64;
        self.phase = self.phase.wrapping_add(increment as u32);
    }

    fn next_noise(&mut self) -> i32 {
        let mut value = self.noise;
        value ^= value << 13;
        value ^= value >> 17;
        value ^= value << 5;
        self.noise = value;
        (value >> 16) as i16 as i32
    }
}

const fn clamp_amplitude(amplitude: Sample) -> u16 {
    let magnitude = amplitude.magnitude();
    if magnitude > i16::MAX as u16 {
        i16::MAX as u16
    } else {
        magnitude
    }
}

fn sine(phase: u32) -> i32 {
    let index = (phase >> 26) as usize;
    let next = (index + 1) & (SINE_TABLE.len() - 1);
    let fraction = ((phase >> 18) & 0xff) as i32;
    let start = SINE_TABLE[index] as i32;
    let end = SINE_TABLE[next] as i32;
    start + (((end - start) * fraction) >> 8)
}

fn triangle(phase: u32) -> i32 {
    let point = (phase >> 16) as i32;
    let value = if point < 0x4000 {
        point * 2
    } else if point < 0xC000 {
        32_767 - (point - 0x4000) * 2
    } else {
        -32_767 + (point - 0xC000) * 2
    };
    value.clamp(-32_767, 32_767)
}

fn sawtooth(phase: u32) -> i32 {
    let point = (phase >> 16) as i32;
    (((point >> 1) - 16_384) * 2).clamp(-32_767, 32_767)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn raw_samples(oscillator: &mut Oscillator, sample_rate: u32, count: usize) -> [i16; 8] {
        let mut values = [0i16; 8];
        for value in values.iter_mut().take(count) {
            *value = oscillator.next_sample(sample_rate).raw();
        }
        values
    }

    #[test]
    fn silence_for_invalid_rate_or_frequency() {
        let mut oscillator = Oscillator::new(Waveform::Sine, 440, Sample::MAX);
        assert_eq!(oscillator.next_sample(0), Sample::SILENCE);

        let mut stopped = Oscillator::new(Waveform::Sine, 0, Sample::MAX);
        assert_eq!(stopped.next_sample(48_000), Sample::SILENCE);
    }

    #[test]
    fn square_period_is_frequency_dependent() {
        let mut oscillator = Oscillator::new(Waveform::Square, 2_000, Sample::from_i16(1_000));
        assert_eq!(
            raw_samples(&mut oscillator, 8_000, 8),
            [1_000, 1_000, -1_000, -1_000, 1_000, 1_000, -1_000, -1_000]
        );
    }

    #[test]
    fn sine_starts_at_zero_and_stays_bounded() {
        let mut oscillator = Oscillator::new(Waveform::Sine, 440, Sample::MAX);
        assert_eq!(oscillator.next_sample(48_000), Sample::SILENCE);

        for _ in 0..1_000 {
            let value = oscillator.next_sample(48_000).raw();
            assert!((-32_767..=32_767).contains(&value), "{value}");
        }
    }

    #[test]
    fn triangle_and_sawtooth_have_expected_endpoints() {
        let mut triangle = Oscillator::new(Waveform::Triangle, 8_000, Sample::MAX);
        assert_eq!(triangle.next_sample(8_000), Sample::SILENCE);

        let mut sawtooth = Oscillator::new(Waveform::Sawtooth, 8_000, Sample::MAX);
        assert_eq!(sawtooth.next_sample(8_000), Sample::from_i16(-32_767));
    }

    #[test]
    fn noise_is_deterministic_and_not_silent() {
        let mut first = Oscillator::new(Waveform::Noise, 1_000, Sample::MAX);
        let mut second = Oscillator::new(Waveform::Noise, 1_000, Sample::MAX);

        let a = raw_samples(&mut first, 48_000, 8);
        let b = raw_samples(&mut second, 48_000, 8);

        assert_eq!(a, b);
        assert!(a.iter().any(|&value| value != 0));
    }

    #[test]
    fn amplitude_scales_output() {
        let mut full = Oscillator::new(Waveform::Square, 2_000, Sample::MAX);
        let mut half = Oscillator::new(Waveform::Square, 2_000, Sample::from_i16(16_383));

        assert_eq!(full.next_sample(8_000).raw(), 32_767);
        assert_eq!(half.next_sample(8_000).raw(), 16_383);

        full.set_amplitude(Sample::SILENCE);
        assert_eq!(full.next_sample(8_000), Sample::SILENCE);
    }

    #[test]
    fn reset_restarts_the_cycle() {
        let mut oscillator = Oscillator::new(Waveform::Square, 2_000, Sample::MAX);
        let first = oscillator.next_sample(8_000);
        let _ = oscillator.next_sample(8_000);
        oscillator.reset();
        assert_eq!(oscillator.next_sample(8_000), first);
    }
}
