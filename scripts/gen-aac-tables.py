#!/usr/bin/env python3
"""Generates libs/audio-codec/src/aac_tables.rs.

    ./scripts/gen-aac-tables.py <ixheaacd_aac_rom.c> > libs/audio-codec/src/aac_tables.rs

The Huffman codebooks and scalefactor band widths are read from libxaac, the
Android Open Source Project's AAC decoder, which is under Apache-2.0. Its source
ships in the `libxaac-sys` crate (version 0.1.0 was used) as
`libxaac/decoder/ixheaacd_aac_rom.c`. The windows are computed here, from the
Kaiser-Bessel-derived formula in ISO/IEC 14496-3.

In that file, a codebook is a list of 16-bit entries in code order, after a first
entry that holds the longest length. Each one is `symbol << 5 | length`, and
the codes are consecutive at each length, so the list fixes the code. This script
checks that each book is a complete prefix code: its Kraft sum is exactly 1.
"""

import math
import re
import sys
from fractions import Fraction

BOOK_SIZES = {1: 81, 2: 81, 3: 81, 4: 81, 5: 81, 6: 81, 7: 64, 8: 64, 9: 169, 10: 169, 11: 289}


def lists_after(source, marker):
    """The brace list that follows a comment."""
    at = source.index(marker)
    start = source.index("{", at)
    end = source.index("}", start)
    return [int(word, 0) for word in re.findall(r"0x[0-9a-fA-F]+|-?\d+", source[start + 1 : end])]


def code_book(entries, size):
    """Turns a list of `symbol << 5 | length` entries into sorted codes."""
    entries = entries[1:]
    if len(entries) != size:
        sys.exit(f"expected {size} entries, found {len(entries)}")
    codes = []
    code = 0
    previous = 0
    kraft = Fraction(0)
    for entry in entries:
        length = entry & 31
        symbol = entry >> 5
        code <<= length - previous
        previous = length
        codes.append((code << (32 - length), length, symbol))
        code += 1
        kraft += Fraction(1, 1 << length)
    if kraft != 1:
        sys.exit(f"a book is not a complete prefix code: Kraft sum {kraft}")
    return sorted(codes)


def book_text(name, codes):
    out = [f"pub(crate) static {name}: [Code; {len(codes)}] = ["]
    for at in range(0, len(codes), 4):
        row = [f"c({code:#010x}, {length}, {symbol})," for code, length, symbol in codes[at : at + 4]]
        out.append("    " + " ".join(row))
    out.append("];")
    return "\n".join(out)


def swb_offsets(widths):
    """Band offsets, from widths ending in -1, one past the last band."""
    offsets = [0]
    for width in widths:
        if width < 0:
            break
        offsets.append(offsets[-1] + width)
    return offsets


def truncated(offsets, end):
    """A 960-sample frame's bands are the 1024-sample ones, stopping where it does."""
    return [value for value in offsets if value < end] + [end]


def swb_text(name, widths, end=None):
    offsets = swb_offsets(widths)
    if end is not None:
        offsets = truncated(offsets, end)
    out = [f"pub(crate) static {name}: [u16; {len(offsets)}] = ["]
    for at in range(0, len(offsets), 14):
        out.append("    " + " ".join(f"{value}," for value in offsets[at : at + 14]))
    out.append("];")
    return "\n".join(out)


def bessel_i0(x):
    total = term = 1.0
    k = 1
    while term > total * 1e-20:
        term *= (x / (2 * k)) ** 2
        total += term
        k += 1
    return total


def kbd_text(name, half, alpha):
    """The rising half of the window, length `half`, in Q31."""
    kaiser = [
        bessel_i0(math.pi * alpha * math.sqrt(1 - (2 * n / half - 1) ** 2)) for n in range(half + 1)
    ]
    total = sum(kaiser)
    values = []
    running = 0.0
    for n in range(half):
        running += kaiser[n]
        values.append(min(round(math.sqrt(running / total) * 2147483648.0), 2147483647))
    out = [f"pub(crate) static {name}: [i32; {half}] = ["]
    for at in range(0, half, 6):
        out.append("    " + " ".join(f"{value}," for value in values[at : at + 6]))
    out.append("];")
    return "\n".join(out)


HEADER = """//! Tables for the AAC decoder. Generated by `scripts/gen-aac-tables.py`.
//!
//! The Huffman codebooks and scalefactor band offsets are the normative tables
//! of ISO/IEC 14496-3, as they appear in libxaac (Android Open Source Project,
//! Apache-2.0). Each code is stored left aligned in 32 bits, sorted, so a
//! decoder finds a symbol by binary search on the next 32 bits of input. The
//! Kaiser-Bessel-derived windows are computed from the formula in the standard.

#![allow(clippy::unreadable_literal)]

/// One Huffman code: left-aligned codeword, its length, and the symbol.
#[derive(Clone, Copy)]
pub(crate) struct Code {
    pub(crate) code: u32,
    pub(crate) length: u8,
    pub(crate) symbol: u16,
}

const fn c(code: u32, length: u8, symbol: u16) -> Code {
    Code { code, length, symbol }
}"""


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    source = open(sys.argv[1], encoding="latin-1").read()
    parts = [HEADER]
    for book, size in BOOK_SIZES.items():
        parts.append(book_text(f"BOOK{book}", code_book(lists_after(source, f"// inp_hf{book}\n"), size)))
    parts.append(
        book_text(
            "SCALEFACTOR",
            code_book(lists_after(source, "// UWORD16 huffman_code_book_scl[122];"), 121),
        )
    )
    parts.append(
        "/// Every spectral codebook, by number minus one.\n"
        "pub(crate) static BOOKS: [&[Code]; 11] = [\n"
        "    &BOOK1, &BOOK2, &BOOK3, &BOOK4, &BOOK5, &BOOK6, &BOOK7, &BOOK8, &BOOK9, &BOOK10, &BOOK11,\n"
        "];"
    )
    for name, marker in [
        ("SWB_L96", "ixheaacd_sfb_96_1024[42]"),
        ("SWB_L64", "ixheaacd_sfb_64_1024[48]"),
        ("SWB_L48", "ixheaacd_sfb_48_1024[50]"),
        ("SWB_L32", "ixheaacd_sfb_32_1024[52]"),
        ("SWB_L24", "ixheaacd_sfb_24_1024[48]"),
        ("SWB_L16", "ixheaacd_sfb_16_1024[44]"),
        ("SWB_L8", "ixheaacd_sfb_8_1024[41]"),
        ("SWB_S96", "ixheaacd_sfb_96_128[13]"),
        ("SWB_S48", "ixheaacd_sfb_48_128[15]"),
        ("SWB_S24", "ixheaacd_sfb_24_128[16]"),
        ("SWB_S16", "ixheaacd_sfb_16_128[16]"),
        ("SWB_S8", "ixheaacd_sfb_8_128[16]"),
    ]:
        parts.append(swb_text(name, lists_after(source, marker)))
        # What the 960-sample frames use.
        end = 960 if name[4] == "L" else 120
        parts.append(swb_text(name + "_FEW", lists_after(source, marker), end))
    parts.append(
        "/// Long and short scalefactor band offsets by sampling frequency index.\n"
        "pub(crate) static SWB_LONG: [&[u16]; 13] = [\n"
        "    &SWB_L96, &SWB_L96, &SWB_L64, &SWB_L48, &SWB_L48, &SWB_L32, &SWB_L24, &SWB_L24, &SWB_L16,\n"
        "    &SWB_L16, &SWB_L16, &SWB_L8, &SWB_L8,\n"
        "];\n"
        "pub(crate) static SWB_SHORT: [&[u16]; 13] = [\n"
        "    &SWB_S96, &SWB_S96, &SWB_S96, &SWB_S48, &SWB_S48, &SWB_S48, &SWB_S24, &SWB_S24, &SWB_S16,\n"
        "    &SWB_S16, &SWB_S16, &SWB_S8, &SWB_S8,\n"
        "];\n"
        "/// The same for 960-sample frames: the same bands, up to where the frame ends.\n"
        "pub(crate) static SWB_LONG_960: [&[u16]; 13] = [\n"
        "    &SWB_L96_FEW, &SWB_L96_FEW, &SWB_L64_FEW, &SWB_L48_FEW, &SWB_L48_FEW, &SWB_L32_FEW, &SWB_L24_FEW,\n"
        "    &SWB_L24_FEW, &SWB_L16_FEW, &SWB_L16_FEW, &SWB_L16_FEW, &SWB_L8_FEW, &SWB_L8_FEW,\n"
        "];\n"
        "pub(crate) static SWB_SHORT_120: [&[u16]; 13] = [\n"
        "    &SWB_S96_FEW, &SWB_S96_FEW, &SWB_S96_FEW, &SWB_S48_FEW, &SWB_S48_FEW, &SWB_S48_FEW, &SWB_S24_FEW,\n"
        "    &SWB_S24_FEW, &SWB_S16_FEW, &SWB_S16_FEW, &SWB_S16_FEW, &SWB_S8_FEW, &SWB_S8_FEW,\n"
        "];"
    )
    parts.append("/// The rising half of the Kaiser-Bessel-derived window, alpha 4, in Q31.\n" + kbd_text("KBD_LONG", 1024, 4))
    parts.append("/// The rising half of the Kaiser-Bessel-derived window, alpha 6, in Q31.\n" + kbd_text("KBD_SHORT", 128, 6))
    parts.append("/// Those windows for 960-sample frames.\n" + kbd_text("KBD_LONG_960", 960, 4))
    parts.append(kbd_text("KBD_SHORT_120", 120, 6))
    print("\n\n".join(parts))


main()
