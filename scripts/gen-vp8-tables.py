#!/usr/bin/env python3
"""Generates libs/video/src/vp8/tables.rs from the text of RFC 6386.

    curl -O https://www.rfc-editor.org/rfc/rfc6386.txt
    ./scripts/gen-vp8-tables.py rfc6386.txt > libs/video/src/vp8/tables.rs

The RFC's reference source is under a BSD licence (its section 20.26), and these are
the format's normative tables. Page breaks are stripped first, as they land in arrays.
"""

import re
import sys

TABLES = [
    # (name in the RFC, Rust name, Rust type, shape)
    ("coeff_update_probs", "COEFF_UPDATE_PROBS", "u8", (4, 8, 3, 11)),
    ("default_coeff_probs", "DEFAULT_COEFF_PROBS", "u8", (4, 8, 3, 11)),
    ("kf_b_mode_probs", "KF_B_MODE_PROBS", "u8", (10, 10, 9)),
    ("dc_qlookup", "DC_Q", "i16", (128,)),
    ("ac_qlookup", "AC_Q", "i16", (128,)),
    ("vp8_mv_update_probs", "MV_UPDATE_PROBS", "u8", (2, 19)),
    ("default_mv_context", "DEFAULT_MV_PROBS", "u8", (2, 19)),
    ("mv_counts_to_probs", "MV_COUNTS_TO_PROBS", "u8", (6, 4)),
    ("submv_ref_probs2", "SUBMV_REF_PROBS", "u8", (5, 3)),
    ("mv_partitions", "MV_PARTITIONS", "u8", (4, 16)),
    ("sixtap_filters", "SIXTAP_FILTERS", "i16", (8, 6)),
    ("bilinear_filters", "BILINEAR_FILTERS", "i16", (8, 6)),
]


def values(text, name, count):
    # The definition: the name, some brackets, an equals sign and a brace.
    for match in re.finditer(re.escape(name) + r"\s*(\[[^\]]*\]\s*)*=\s*\{", text):
        body = text[match.end():]
        body = re.sub(r"/\*.*?\*/", " ", body, flags=re.S)
        body = re.sub(r"//[^\n]*", " ", body)
        depth, end = 1, 0
        while depth:
            character = body[end]
            depth += {"{": 1, "}": -1}.get(character, 0)
            end += 1
        numbers = [int(n) for n in re.findall(r"-?\b\d+\b", body[:end])]
        if len(numbers) == count:
            return numbers
    sys.exit(f"no {name} with {count} values")


def emit(numbers, shape, indent=0):
    pad = " " * indent
    if len(shape) == 1:
        return pad + "[" + ", ".join(str(n) for n in numbers) + "]"
    step = len(numbers) // shape[0]
    rows = [emit(numbers[i * step : (i + 1) * step], shape[1:], indent + 4) for i in range(shape[0])]
    return pad + "[\n" + ",\n".join(rows) + ",\n" + pad + "]"


def main():
    text = open(sys.argv[1], encoding="latin-1").read().replace("\f", "\n")
    text = "\n".join(
        line for line in text.split("\n") if not re.match(r"^(Bankoski, et al\.|RFC 6386 )", line)
    )
    print("//! The tables of the VP8 format. Generated by `scripts/gen-vp8-tables.py` from RFC 6386.")
    print()
    for name, rust, kind, shape in TABLES:
        count = 1
        for size in shape:
            count *= size
        numbers = values(text, name, count)
        ty = kind
        for size in reversed(shape):
            ty = f"[{ty}; {size}]"
        print(f"pub(super) static {rust}: {ty} = {emit(numbers, shape)};")
        print()


main()
