//! Generates the embedded application folder for the desktop app.
//!
//! Every non-hidden file in `apps/` becomes a [`DirEntry`] in the generated
//! `folder.rs`. The desktop then scans that folder at run time, exactly like a
//! filesystem-backed board would scan a real directory. To add an application,
//! drop a `.fapp` bundle into `apps/` and rebuild; nothing else changes.

use std::env;
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    println!("cargo:rerun-if-changed=apps");

    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("manifest dir"));
    let folder = manifest_dir.join("apps");
    let mut files: Vec<(String, PathBuf)> = Vec::new();

    if let Ok(entries) = fs::read_dir(&folder) {
        for entry in entries.flatten() {
            let path = entry.path();
            if !path.is_file() {
                continue;
            }
            let name = entry.file_name().to_string_lossy().into_owned();
            if name.starts_with('.') {
                continue;
            }
            files.push((name, path));
        }
    }
    files.sort_by(|left, right| left.0.cmp(&right.0));

    let mut generated = String::new();
    generated.push_str("// @generated by build.rs - do not edit.\n");
    generated.push_str("/// Bundles found in the compile-time application folder.\n");
    generated.push_str("pub static FOLDER: &[feos_desktop::DirEntry<'static>] = &[\n");
    for (name, path) in &files {
        generated.push_str(&format!(
            "    feos_desktop::DirEntry::new({name:?}, include_bytes!({path:?})),\n",
            name = name,
            path = path.to_string_lossy().as_ref(),
        ));
    }
    generated.push_str("];\n");

    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("out dir"));
    write_if_changed(&out_dir.join("folder.rs"), &generated);
}

fn write_if_changed(path: &Path, contents: &str) {
    if let Ok(existing) = fs::read_to_string(path) {
        if existing == contents {
            return;
        }
    }
    fs::write(path, contents).expect("write generated folder");
}
