/// The glyph for `ch`, or `?` for one there isn't.
pub fn glyph(ch: char) -> &'static [u8; 7] {
    let code = ch as u32;
    if (32..127).contains(&code) {
        &GLYPHS[(code - 32) as usize]
    } else {
        &GLYPHS[('?' as u32 - 32) as usize]
    }
}

/// Draws `text` from (`x`, `y`), clipped to columns before `right`. Returns
/// where the next character would go.
pub fn draw(canvas: &mut Canvas<'_>, x: i32, y: i32, text: &str, color: Color, right: i32) -> i32 {
    let mut at = x;
    for ch in text.chars() {
        if at >= right {
            break;
        }
        draw_char(canvas, at, y, ch, color, right);
        at += ADVANCE;
    }
    at
}

/// Draws one character, clipped to columns before `right`.
pub fn draw_char(canvas: &mut Canvas<'_>, x: i32, y: i32, ch: char, color: Color, right: i32) {
    for (row, bits) in glyph(ch).iter().enumerate() {
        for column in 0..5 {
            if bits & (0x10 >> column) != 0 && x + column < right {
                canvas.put_pixel(x + column, y + row as i32, color);
            }
        }
    }
}

/// How wide `text` is drawn.
pub fn width(text: &str) -> i32 {
    text.chars().count() as i32 * ADVANCE
}

/// A 3 by 5 font for labels where the 5 by 7 won't fit: digits, K, signs, d, b.
const TINY: [(char, [u8; 5]); 15] = [
    ('0', [7, 5, 5, 5, 7]),
    ('1', [2, 6, 2, 2, 7]),
    ('2', [7, 1, 7, 4, 7]),
    ('3', [7, 1, 3, 1, 7]),
    ('4', [5, 5, 7, 1, 1]),
    ('5', [7, 4, 7, 1, 7]),
    ('6', [7, 4, 7, 5, 7]),
    ('7', [7, 1, 2, 2, 2]),
    ('8', [7, 5, 7, 5, 7]),
    ('9', [7, 5, 7, 1, 7]),
    ('K', [5, 6, 4, 6, 5]),
    ('+', [0, 2, 7, 2, 0]),
    ('-', [0, 0, 7, 0, 0]),
    ('d', [1, 1, 7, 5, 7]),
    ('b', [4, 4, 7, 5, 7]),
];

/// Pixels from one tiny character to the next.
pub const TINY_ADVANCE: i32 = 4;

/// Draws `text` in the tiny font; characters it doesn't have are spaces.
pub fn draw_tiny(canvas: &mut Canvas<'_>, x: i32, y: i32, text: &str, color: Color) {
    for (index, ch) in text.chars().enumerate() {
        let Some((_, rows)) = TINY.iter().find(|(known, _)| *known == ch) else {
            continue;
        };
        let at = x + index as i32 * TINY_ADVANCE;
        for (row, bits) in rows.iter().enumerate() {
            for column in 0..3 {
                if bits & (4 >> column) != 0 {
                    canvas.put_pixel(at + column, y + row as i32, color);
                }
            }
        }
    }
}

/// How wide `text` is in the tiny font.
pub fn tiny_width(text: &str) -> i32 {
    (text.chars().count() as i32 * TINY_ADVANCE - 1).max(0)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_printable_character_has_a_glyph() {
        assert!(glyph(' ').iter().all(|row| *row == 0));
        assert!(glyph('A').iter().any(|row| *row != 0));
        assert_eq!(glyph('\u{263a}'), glyph('?'));
        assert_eq!(width("abc"), 18);
    }

    #[test]
    fn drawing_clips_on_the_right() {
        let mut pixels = [0u32; 20 * 8];
        let mut canvas = Canvas::new(&mut pixels, 20, 8, 20).unwrap();
        let next = draw(&mut canvas, 0, 0, "MMMMM", Color::WHITE, 8);
        assert_eq!(next, 12);
        assert!(pixels.iter().enumerate().all(|(i, p)| *p == 0 || i % 20 < 8));
    }
}
