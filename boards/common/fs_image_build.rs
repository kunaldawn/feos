//! Generates the embedded read-only filesystem image, for both boards' build
//! scripts, which include this file.
//!
//! Every file and directory under `fs/` becomes a `feos_fs::StaticNode` in the
//! generated `fs_image.rs`. Dropping a file into `fs/` and rebuilding is enough
//! for it to show up in the file explorer and the shell's `files` command.

use std::collections::BTreeMap;
use std::env;
use std::fs;
use std::path::{Path, PathBuf};

struct EntryInfo {
    name: String,
    is_dir: bool,
    file: Option<PathBuf>,
    parent: Option<usize>,
    children: Vec<usize>,
}

/// Writes `fs_image.rs` from `data_dir/fs` and the optional disk images beside it.
pub fn generate(data_dir: &Path) {
    // Naming a file that doesn't exist makes Cargo treat this build as stale on
    // every run, which relinks the kernel. Watching the directory notices the
    // optional disk images appearing, whichever of them do exist. It also covers
    // the sample tree under `fs/`.
    println!("cargo:rerun-if-changed={}", data_dir.display());

    let root = data_dir.join("fs");

    let mut found = Vec::new();
    collect(&root, "", &mut found);
    collect_user_programs(data_dir, &mut found);
    found.sort_by(|left, right| left.0.cmp(&right.0));

    let mut entries = std::vec![EntryInfo {
        name: String::from("/"),
        is_dir: true,
        file: None,
        parent: None,
        children: Vec::new(),
    }];
    let mut index = BTreeMap::new();
    index.insert(String::new(), 0usize);

    for (rel, is_dir, path) in found {
        let name = rel.rsplit('/').next().unwrap_or(&rel).to_string();
        let parent_rel = match rel.rfind('/') {
            Some(position) => rel[..position].to_string(),
            None => String::new(),
        };
        let Some(&parent) = index.get(&parent_rel) else {
            continue;
        };

        let id = entries.len();
        entries.push(EntryInfo {
            name,
            is_dir,
            file: if is_dir { None } else { Some(path) },
            parent: Some(parent),
            children: Vec::new(),
        });
        index.insert(rel, id);
        entries[parent].children.push(id);
    }

    let mut generated = String::new();
    generated.push_str("// @generated by build.rs - do not edit.\n");
    generated.push_str("pub static FS_IMAGE: &[feos_fs::StaticNode] = &[\n");
    for entry in &entries {
        let parent = match entry.parent {
            Some(id) => format!("Some({id})"),
            None => String::from("None"),
        };
        if entry.is_dir {
            let children = entry
                .children
                .iter()
                .map(usize::to_string)
                .collect::<std::vec::Vec<_>>()
                .join(", ");
            generated.push_str(&format!(
                "    feos_fs::StaticNode::dir({:?}, {parent}, &[{children}]),\n",
                entry.name
            ));
        } else {
            let path = entry
                .file
                .as_ref()
                .expect("file entry has a path")
                .to_string_lossy();
            generated.push_str(&format!(
                "    feos_fs::StaticNode::file({:?}, {parent}, include_bytes!({:?})),\n",
                entry.name,
                path.as_ref()
            ));
        }
    }
    generated.push_str("];\n");

    // An optional FAT32 or exFAT disk image can be dropped next to the board's
    // embedded tree. It is mounted read-only at boot and takes precedence over
    // the compiled-in StaticFs image.
    let disk = data_dir.join("disk.img");
    if disk.is_file() {
        generated.push_str(&format!(
            "pub static DISK_IMAGE: Option<&'static [u8]> = Some(include_bytes!({:?}));\n",
            disk.to_string_lossy().as_ref()
        ));
    } else {
        generated.push_str("pub static DISK_IMAGE: Option<&'static [u8]> = None;\n");
    }

    // Test volumes used by `make docker-run`. Each is exposed under its own
    // top-level directory when present.
    for (name, file) in [
        ("DISK_FAT32_IMAGE", "disk-fat32.img"),
        ("DISK_EXFAT_IMAGE", "disk-exfat.img"),
    ] {
        let path = data_dir.join(file);
        if path.is_file() {
            generated.push_str(&format!(
                "pub static {name}: Option<&'static [u8]> = Some(include_bytes!({:?}));\n",
                path.to_string_lossy().as_ref()
            ));
        } else {
            generated.push_str(&format!(
                "pub static {name}: Option<&'static [u8]> = None;\n"
            ));
        }
    }

    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("out dir"));
    write_if_changed(&out_dir.join("fs_image.rs"), &generated);
}

fn collect(dir: &Path, prefix: &str, out: &mut Vec<(String, bool, PathBuf)>) {
    let Ok(entries) = fs::read_dir(dir) else {
        return;
    };
    let mut items: std::vec::Vec<_> = entries.flatten().collect();
    items.sort_by_key(|entry| entry.file_name());

    for entry in items {
        let path = entry.path();
        let name = entry.file_name().to_string_lossy().into_owned();
        if name.starts_with('.') {
            continue;
        }
        let rel = if prefix.is_empty() {
            name
        } else {
            format!("{prefix}/{name}")
        };

        if path.is_dir() {
            out.push((rel.clone(), true, path.clone()));
            collect(&path, &rel, out);
        } else if path.is_file() {
            out.push((rel, false, path));
        }
    }
}

fn write_if_changed(path: &Path, contents: &str) {
    if let Ok(existing) = fs::read_to_string(path) {
        if existing == contents {
            return;
        }
    }
    fs::write(path, contents).expect("write generated fs image");
}

/// Adds the user programs built for this architecture, if `make user-arm` or `make
/// user-x64` has built them, as `/bin`. A kernel built without them works, with no
/// programs.
fn collect_user_programs(data_dir: &Path, found: &mut Vec<(String, bool, PathBuf)>) {
    let Ok(arch) = env::var("CARGO_CFG_TARGET_ARCH") else {
        return;
    };
    let user = data_dir.join("../../user");
    let programs = user.join("out").join(&arch);
    // Only names something that exists, for the reason at the top of `generate`.
    if programs.is_dir() {
        println!("cargo:rerun-if-changed={}", programs.display());
    } else {
        println!("cargo:rerun-if-changed={}", user.join("Cargo.toml").display());
    }
    let Ok(entries) = fs::read_dir(&programs) else {
        return;
    };
    found.push((String::from("bin"), true, programs.clone()));
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_file() {
            let name = entry.file_name().to_string_lossy().into_owned();
            found.push((format!("bin/{name}"), false, path));
        }
    }
}
